const Lang = {
  current: localStorage.getItem("ca_lang") || "en",
  t(key) {
    const dict = I18N[this.current] || I18N.en;
    return dict[key] !== undefined ? dict[key] : (I18N.en[key] !== undefined ? I18N.en[key] : key);
  },
  set(lang) {
    this.current = I18N[lang] ? lang : "en";
    localStorage.setItem("ca_lang", this.current);
    document.documentElement.lang = this.current;
    document.dispatchEvent(new CustomEvent("langchange", { detail: this.current }));
  },
  toggle() { this.set(this.current === "en" ? "kn" : "en"); }
};
const t = (k) => Lang.t(k);
window.Lang = Lang; window.t = t;
